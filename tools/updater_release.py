#!/usr/bin/env python3
"""Create one verified Tauri manifest from the final GitHub release assets.

Requires cryptography for Ed25519 verification. Never reads the signing private key.
"""
import argparse
import base64
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import tomllib
from urllib.parse import quote

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey


def normalized_version(tag):
    version = tag.removeprefix("v")
    if not re.fullmatch(r"(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)(?:-[0-9A-Za-z.-]+)?(?:\+[0-9A-Za-z.-]+)?", version):
        raise ValueError("Invalid release version")
    return version


def verify_signature(artifact, signature, public_key):
    """Verify Tauri's base64-wrapped Minisign packet and its trusted comment."""
    try:
        public_lines = base64.b64decode(public_key.strip(), validate=True).splitlines()
        public = base64.b64decode(public_lines[1], validate=True)
        lines = base64.b64decode(signature.strip(), validate=True).splitlines()
        packet = base64.b64decode(lines[1], validate=True)
        if len(public) != 42 or public[:2] != b"Ed" or len(packet) != 74:
            raise ValueError("Invalid Minisign packet")
        if packet[2:10] != public[2:10] or packet[:2] not in (b"ED", b"Ed"):
            raise ValueError("Signature key does not match the application public key")
        if len(lines) != 4 or not lines[2].startswith(b"trusted comment: "):
            raise ValueError("Missing trusted comment")
        key = Ed25519PublicKey.from_public_bytes(public[10:])
        if packet[:2] == b"ED":
            digest = hashlib.blake2b(digest_size=64)
            with artifact.open("rb") as source:
                for chunk in iter(lambda: source.read(1024 * 1024), b""):
                    digest.update(chunk)
            content = digest.digest()
        else:
            content = artifact.read_bytes()
        key.verify(packet[10:], content)
        key.verify(base64.b64decode(lines[3], validate=True), packet[10:] + lines[2][17:])
    except Exception as error:
        raise ValueError(f"Invalid signature for {artifact.name}") from error


def build_manifest(assets_dir, tag, repo, public_key, notes):
    version = normalized_version(tag)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", repo):
        raise ValueError("Invalid repository")
    version_pattern = re.escape(version)
    # macOS archive names are generated by tauri-action and include architecture, not version.
    patterns = {
        "windows-x86_64-nsis": rf".+_{version_pattern}_(?:x64|x86_64)-setup\.exe",
        "windows-x86_64-msi": rf".+_{version_pattern}_(?:x64|x86_64)(?:_[A-Za-z-]+)?\.msi",
        "darwin-x86_64": r".+_(?:x64|x86_64)\.app\.tar\.gz",
        "darwin-aarch64": r".+_aarch64\.app\.tar\.gz",
        "linux-x86_64": rf".+_{version_pattern}_(?:amd64|x86_64)\.AppImage",
    }
    platforms = {}
    for target, pattern in patterns.items():
        matches = [path for path in assets_dir.iterdir() if path.is_file() and re.fullmatch(pattern, path.name)]
        if len(matches) != 1:
            raise ValueError(f"Expected exactly one {target} artifact for version {version}; found {len(matches)}")
        artifact = matches[0]
        signature_file = Path(str(artifact) + ".sig")
        if not signature_file.is_file():
            raise ValueError(f"Missing signature for {artifact.name}")
        signature = signature_file.read_text(encoding="utf-8").strip()
        verify_signature(artifact, signature, public_key)
        platforms[target] = {
            "url": f"https://github.com/{repo}/releases/download/{quote(tag, safe='')}/{quote(artifact.name, safe='')}",
            "signature": signature,
        }
    # New clients choose the installer-specific entry; this is the legacy fallback.
    platforms["windows-x86_64"] = dict(platforms["windows-x86_64-nsis"])
    return {"version": version, "notes": notes,
            "pub_date": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"), "platforms": platforms}


def validate_source_versions(root, tag):
    expected = normalized_version(tag)
    values = {
        "Cargo.toml": tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8"))["workspace"]["package"]["version"],
        "package.json": json.loads((root / "package.json").read_text(encoding="utf-8"))["version"],
        "apps/desktop/package.json": json.loads((root / "apps/desktop/package.json").read_text(encoding="utf-8"))["version"],
        "apps/desktop/src-tauri/tauri.conf.json": json.loads((root / "apps/desktop/src-tauri/tauri.conf.json").read_text(encoding="utf-8"))["version"],
    }
    for name, actual in values.items():
        if actual != expected:
            raise ValueError(f"Release version {expected} does not match {name}: {actual}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["preflight", "manifest"])
    parser.add_argument("--tag", required=True)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--assets-dir", type=Path)
    parser.add_argument("--release-json", type=Path)
    parser.add_argument("--repo", default="dilukshann7/dlman")
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    validate_source_versions(args.root, args.tag)
    if args.command == "preflight":
        return
    if not all([args.assets_dir, args.release_json, args.output]):
        parser.error("manifest requires --assets-dir, --release-json and --output")
    release = json.loads(args.release_json.read_text(encoding="utf-8"))
    if release["tagName"] != args.tag or not release["isDraft"]:
        raise ValueError("Updater assets must be assembled on the matching draft release")
    if release["isPrerelease"] != ("-" in normalized_version(args.tag)):
        raise ValueError("Release prerelease status does not match its version")
    config = json.loads((args.root / "apps/desktop/src-tauri/tauri.conf.json").read_text(encoding="utf-8"))
    manifest = build_manifest(args.assets_dir, args.tag, args.repo, config["plugins"]["updater"]["pubkey"], release["body"])
    names = {asset["name"] for asset in release["assets"]}
    for entry in manifest["platforms"].values():
        from urllib.parse import unquote
        name = unquote(entry["url"].rsplit("/", 1)[-1])
        if name not in names or name + ".sig" not in names:
            raise ValueError(f"Referenced updater asset is absent from release: {name}")
    args.output.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(f"Verified {len(manifest['platforms'])} updater targets for {args.tag}")


if __name__ == "__main__":
    main()
